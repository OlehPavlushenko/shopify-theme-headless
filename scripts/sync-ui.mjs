// Copies the shared UI package into the theme: packages/ui/{css,js}/<name> -> theme/assets/ui-<name>,
// and joins the stylesheets every page needs into theme/assets/ui-core.css (see CORE).
// theme/assets/ui-* files are generated: edit packages/ui instead. Stale ui-* files are removed.
// Usage: node scripts/sync-ui.mjs [--watch]
import { existsSync, readdirSync, readFileSync, unlinkSync, watch, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['css', 'js'].map((dir) => join(root, 'packages', 'ui', dir));
const assets = join(root, 'theme', 'assets');

// The render-blocking stylesheets of every page (layout/theme.liquid), in cascade order, as one file:
// one request instead of nine, and Shopify's preload Link headers (10 at most, render-blocking
// styles first) keep room for the page's main image. The sources stay separate for a headless app.
const CORE = ['tokens', 'base', 'components', 'product-card', 'slider', 'announcements', 'header', 'blocks', 'sections'];

const banner = (ext, from) =>
  ext === 'css' || ext === 'js' ? `/* Generated from ${from} by scripts/sync-ui.mjs. Do not edit here. */\n` : '';

function sync() {
  const expected = new Set();
  for (const dir of sources) {
    if (!existsSync(dir)) continue;
    for (const name of readdirSync(dir)) {
      if (name.startsWith('_')) continue;
      const ext = name.split('.').pop();
      const target = `ui-${name}`;
      const from = `packages/ui/${dir.split(/[\\/]/).pop()}/${name}`;
      const content = banner(ext, from) + readFileSync(join(dir, name), 'utf8');
      const out = join(assets, target);
      expected.add(target);
      if (!existsSync(out) || readFileSync(out, 'utf8') !== content) {
        writeFileSync(out, content);
        console.log(`sync: ${from} -> theme/assets/${target}`);
      }
    }
  }
  const coreDir = join(root, 'packages', 'ui', 'css');
  const core =
    `/* Generated by scripts/sync-ui.mjs from packages/ui/css: ${CORE.join(', ')}. Do not edit here. */\n` +
    CORE.map((name) => `/* ---- ${name}.css */\n` + readFileSync(join(coreDir, `${name}.css`), 'utf8')).join('\n');
  const coreOut = join(assets, 'ui-core.css');
  expected.add('ui-core.css');
  if (!existsSync(coreOut) || readFileSync(coreOut, 'utf8') !== core) {
    writeFileSync(coreOut, core);
    console.log('sync: core stylesheets -> theme/assets/ui-core.css');
  }
  for (const name of readdirSync(assets)) {
    if (name.startsWith('ui-') && !expected.has(name)) {
      unlinkSync(join(assets, name));
      console.log(`sync: removed stale theme/assets/${name}`);
    }
  }
}

sync();

if (process.argv.includes('--watch')) {
  let timer;
  for (const dir of sources) {
    if (!existsSync(dir)) continue;
    watch(dir, () => {
      clearTimeout(timer);
      timer = setTimeout(sync, 100);
    });
  }
  console.log('sync: watching packages/ui');
}
