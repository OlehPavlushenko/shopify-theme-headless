// Builds packages/ui/css/tokens.css from tokens.json.
// Every leaf becomes a custom property named after its path; a "DEFAULT" key adds no suffix.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const tokens = JSON.parse(readFileSync(join(here, 'tokens.json'), 'utf8'));

const lines = [];
(function walk(node, path) {
    for (const [key, value] of Object.entries(node)) {
        if (key.startsWith('$')) continue;
        const next = key === 'DEFAULT' ? path : [...path, key];
        if (value !== null && typeof value === 'object') walk(value, next);
        else lines.push(`    --${next.join('-')}: ${value};`);
    }
})(tokens, []);

const css = `/* Generated by packages/tokens/build.mjs from tokens.json. Do not edit. */
@layer reset, base, layout, components, utilities;

@layer base {
  :root {
${lines.join('\n')}
  }
}
`;

const out = join(here, '..', 'ui', 'css', 'tokens.css');
writeFileSync(out, css);
console.log(`tokens: ${lines.length} custom properties -> ${out}`);
